create or replace function public.get_posts_with_counts()
returns table (
  id integer,
  title text,
  content text,
  created_at timestamptz,
  image_url text,
  avatar_url text,
  like_count integer,
  comment_count integer
)
language sql
stable
set search_path = ''
as $$
  select
    p.id,
    p.title,
    p.content,
    p.created_at,
    p.image_url,
    p.avatar_url,
    (select count(*)::integer from public.votes v where v.post_id = p.id and v.vote = 1),
    (select count(*)::integer from public.comments c where c.post_id = p.id)
  from public.posts p
  order by p.created_at desc;
$$;

