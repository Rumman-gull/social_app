create table if not exists public.communities (
  id integer generated by default as identity primary key,
  name text not null unique,
  description text not null default '',
  created_by uuid not null default auth.uid() references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.posts (
  id integer generated by default as identity primary key,
  title text not null,
  content text not null,
  image_url text,
  avatar_url text,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  community_id integer references public.communities (id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.votes (
  id integer generated by default as identity primary key,
  post_id integer not null references public.posts (id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  vote integer not null check (vote in (-1, 1)),
  created_at timestamptz not null default now(),
  unique (post_id, user_id)
);

create table if not exists public.comments (
  id integer generated by default as identity primary key,
  post_id integer not null references public.posts (id) on delete cascade,
  parent_comment_id integer references public.comments (id) on delete cascade,
  content text not null,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  author text not null,
  created_at timestamptz not null default now()
);

create index if not exists posts_community_id_idx on public.posts (community_id);
create index if not exists posts_created_at_idx on public.posts (created_at desc);
create index if not exists votes_post_id_idx on public.votes (post_id);
create index if not exists comments_post_id_created_at_idx
  on public.comments (post_id, created_at);

alter table public.communities enable row level security;
alter table public.posts enable row level security;
alter table public.votes enable row level security;
alter table public.comments enable row level security;

